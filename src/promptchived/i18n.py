def language_from_request(request: Request) -> str:
    language = request.cookies.get("promptchived_language", DEFAULT_LANGUAGE)
    return language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def translator(language: str) -> Callable[..., str]:
    def translate(key: str, **values: object) -> str:
        template = TRANSLATIONS.get(language, TRANSLATIONS[DEFAULT_LANGUAGE]).get(
            key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
        )
        return template.format(**values)

    return translate
